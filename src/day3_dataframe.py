def write_pointer(
    pointer_file,
    target_folder
):

    """
    Safely updates the pointer file.

    The actual target folder is never modified.
    """

    temp_pointer = pointer_file.with_suffix(
        ".tmp"
    )

    temp_pointer.write_text(
        str(target_folder.resolve()),
        encoding="utf-8"
    )

    os.replace(
        temp_pointer,
        pointer_file
    )


