def save_change_history(change_rows):

    if not change_rows:
        return

    conn = sqlite3.connect(AUDIT_DB)

    cursor = conn.cursor()

    for row in change_rows:

        cursor.execute(
            """
            INSERT INTO etl_change_history
            (
                ChangeID,
                RunID,
                ChangeTime,
                ShipmentID,
                ColumnName,
                OldValue,
                NewValue
            )
            VALUES (?, ?, ?, ?, ?, ?, ?)
            """,
            (
                str(uuid.uuid4()),
                RUN_ID,
                datetime.now().isoformat(),
                str(row["ShipmentID"]),
                row["ColumnName"],
                row["OldValue"],
                row["NewValue"]
            )
        )

    conn.commit()
    conn.close()

    print(
        f"Change history saved: {len(change_rows)} changes."
    )

