# 20. WRITE PARQUET
# ============================================================

def write_parquet(
    df,
    output_folder
):

    record_count = df.count()

    print()
    print(
        f"Writing {record_count} records to:"
    )

    print(output_folder)


    # ========================================================
    # SMALL DATASET
    # ========================================================

    if record_count <= PARTITION_THRESHOLD:

        print(
            "Dataset is small -> "
            "using 1 partition."
        )

        df = df.coalesce(1)


    # ========================================================
    # LARGE DATASET
    # ========================================================

    else:

        print(
            "Dataset is large -> "
            f"using {LARGE_DATASET_PARTITIONS} "
            "partitions."
        )

        df = df.repartition(
            LARGE_DATASET_PARTITIONS
        )


    # ========================================================
    # WRITE
    # ========================================================

    (
        df.write
        .mode("overwrite")
        .parquet(
            str(output_folder)
        )
    )


