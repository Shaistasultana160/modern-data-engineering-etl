# 13. CHECK TARGET SCHEMA
# ============================================================

def target_schema_is_compatible(target_df):

    """
    Checks whether the existing target contains
    all columns required by the new 8-column design.

    This is important because the project previously
    used a 5-column source/target.
    """

    if target_df is None:

        return False

    required_target_columns = (
        ["ShipmentID"]
        + COMPARE_COLUMNS
    )

    missing_columns = [
        column_name
        for column_name in required_target_columns
        if column_name not in target_df.columns
    ]

    if missing_columns:

        print()
        print("Existing target schema is OLD.")

        print(
            "Missing columns:"
        )

        for column_name in missing_columns:

            print(
                f"  - {column_name}"
            )

        print()
        print(
            "The ETL will automatically rebuild "
            "the baseline using the current "
            "8-column source."
        )

        return False

    print()
    print(
        "Existing target schema is compatible."
    )

    return True


