def initialize_audit_db():
    '''
    Creates the audit table if it does not exist.

    Also safely migrates the older audit-table schema used by
    the previous version of this project. Existing audit history
    is preserved; missing columns are added automatically.
    '''

    AUDIT_DB.parent.mkdir(parents=True, exist_ok=True)

    conn = sqlite3.connect(AUDIT_DB)
    cursor = conn.cursor()

    cursor.execute(
        '''
        CREATE TABLE IF NOT EXISTS etl_audit_log
        (
            RunID TEXT PRIMARY KEY,
            StartTime TEXT,
            EndTime TEXT,
            Status TEXT,
            InsertedRecords INTEGER DEFAULT 0,
            UpdatedRecords INTEGER DEFAULT 0,
            UnchangedRecords INTEGER DEFAULT 0,
            ValidRecords INTEGER DEFAULT 0,
            InvalidRecords INTEGER DEFAULT 0,
            DurationSeconds REAL DEFAULT 0,
            ErrorMessage TEXT
        )
        '''
    )

    # --------------------------------------------------------
    # Migrate an existing older audit table.
    # CREATE TABLE IF NOT EXISTS does not alter an existing
    # SQLite table, so add missing columns explicitly.
    # --------------------------------------------------------

    cursor.execute("PRAGMA table_info(etl_audit_log)")
    existing_columns = {
        row[1]
        for row in cursor.fetchall()
    }

    required_columns = {
        "RunID": "TEXT",
        "StartTime": "TEXT",
        "EndTime": "TEXT",
        "Status": "TEXT",
        "InsertedRecords": "INTEGER",
        "UpdatedRecords": "INTEGER",
        "UnchangedRecords": "INTEGER",
        "ValidRecords": "INTEGER",
        "InvalidRecords": "INTEGER",
        "DurationSeconds": "REAL",
        "ErrorMessage": "TEXT",
    }

    for column_name, data_type in required_columns.items():

        if column_name not in existing_columns:

            cursor.execute(
                f'ALTER TABLE etl_audit_log '
                f'ADD COLUMN "{column_name}" {data_type}'
            )

    # Preserve counts from the old audit schema.
    old_to_new = {
        "Inserted": "InsertedRecords",
        "Updated": "UpdatedRecords",
        "Unchanged": "UnchangedRecords",
    }

    for old_column, new_column in old_to_new.items():

        if old_column in existing_columns:

            cursor.execute(
                f'''
                UPDATE etl_audit_log
                SET "{new_column}" =
                    COALESCE("{new_column}", "{old_column}")
                WHERE "{new_column}" IS NULL
                '''
            )

    # --------------------------------------------------------
    # Detailed change history.
    # One row is stored for each changed source/business column.
    # --------------------------------------------------------

    cursor.execute(
        """
        CREATE TABLE IF NOT EXISTS etl_change_history
        (
            ChangeID TEXT PRIMARY KEY,
            RunID TEXT,
            ChangeTime TEXT,
            ShipmentID TEXT,
            ColumnName TEXT,
            OldValue TEXT,
            NewValue TEXT
        )
        """
    )

    conn.commit()
    conn.close()


initialize_audit_db()


