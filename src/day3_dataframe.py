# 19. INCREMENTAL PROCESSING
# ============================================================

def process_incremental(
    source_df,
    target_df
):

    """
    Returns:

        final_df
        inserted_count
        updated_count
        unchanged_count
        change_history_df
    """

    # ========================================================
    # FIRST RUN / SCHEMA MIGRATION
    # ========================================================

    if target_df is None:

        print()
        print(
            "No compatible target found."
        )

        print(
            "Current source will become "
            "the new baseline."
        )

        inserted_count = source_df.count()

        return (
            source_df,
            inserted_count,
            0,
            0,
            None
        )


    # ========================================================
    # INSERTED RECORDS
    # ========================================================

    inserted_df = (
        source_df.alias("src")
        .join(
            target_df.alias("tgt"),
            col("src.ShipmentID")
            ==
            col("tgt.ShipmentID"),
            "left_anti"
        )
    )


    # ========================================================
    # EXISTING RECORDS
    # ========================================================

    existing_df = (
        source_df.alias("src")
        .join(
            target_df.alias("tgt"),
            col("src.ShipmentID")
            ==
            col("tgt.ShipmentID"),
            "inner"
        )
    )


    # ========================================================
    # CHANGE DETECTION
    # ========================================================

    change_condition = None

    for column_name in COMPARE_COLUMNS:

        condition = ~(
            col(
                f"src.{column_name}"
            ).eqNullSafe(
                col(
                    f"tgt.{column_name}"
                )
            )
        )

        if change_condition is None:

            change_condition = condition

        else:

            change_condition = (
                change_condition
                |
                condition
            )


    # ========================================================
    # UPDATED RECORDS
    # ========================================================

    updated_existing_df = (
        existing_df
        .filter(change_condition)
    )

    updated_df = (
        updated_existing_df
        .select("src.*")
    )


    # ========================================================
    # BUILD DETAILED CHANGE HISTORY
    # ========================================================

    change_history_df = None

    for column_name in COMPARE_COLUMNS:

        column_changes = (
            updated_existing_df
            .select(
                col("src.ShipmentID").alias("ShipmentID"),
                col(f"tgt.{column_name}")
                .cast("string")
                .alias("OldValue"),
                col(f"src.{column_name}")
                .cast("string")
                .alias("NewValue")
            )
            .filter(
                ~col("OldValue").eqNullSafe(
                    col("NewValue")
                )
            )
            .withColumn(
                "ColumnName",
                lit(column_name)
            )
            .select(
                "ShipmentID",
                "ColumnName",
                "OldValue",
                "NewValue"
            )
        )

        if change_history_df is None:

            change_history_df = column_changes

        else:

            change_history_df = (
                change_history_df
                .unionByName(column_changes)
            )


    # ========================================================
    # UNCHANGED
    # ========================================================

    unchanged_df = (
        existing_df
        .filter(~change_condition)
        .select("src.*")
    )


    # ========================================================
    # COUNTS
    # ========================================================

    inserted_count = inserted_df.count()

    updated_count = updated_df.count()

    unchanged_count = unchanged_df.count()


    # ========================================================
    # OLD RECORDS NOT PRESENT IN SOURCE
    # ========================================================

    old_records_to_keep = (
        target_df.alias("tgt")
        .join(
            source_df.alias("src"),
            col("tgt.ShipmentID")
            ==
            col("src.ShipmentID"),
            "left_anti"
        )
    )


    # ========================================================
    # FINAL DATASET
    # ========================================================

    final_df = (
        old_records_to_keep
        .unionByName(
            inserted_df
        )
        .unionByName(
            updated_df
        )
        .unionByName(
            unchanged_df
        )
    )


    return (
        final_df,
        inserted_count,
        updated_count,
        unchanged_count,
        change_history_df
    )


