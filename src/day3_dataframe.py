# 17. CLEAN AND TRANSFORM
# ============================================================

def transform_data(df):

    print()
    print(
        "Cleaning and transforming data..."
    )

    df = (
        df

        # ----------------------------------------------------
        # Clean Customer
        # ----------------------------------------------------

        .withColumn(
            "Customer",
            initcap(
                trim(
                    col("Customer")
                )
            )
        )

        # ----------------------------------------------------
        # Clean City
        # ----------------------------------------------------

        .withColumn(
            "City",
            initcap(
                trim(
                    col("City")
                )
            )
        )

        # ----------------------------------------------------
        # Clean Status
        # ----------------------------------------------------

        .withColumn(
            "Status",
            initcap(
                trim(
                    col("Status")
                )
            )
        )

        # ----------------------------------------------------
        # Convert ShipmentDate
        # ----------------------------------------------------

        .withColumn(
            "ShipmentDate",
            to_date(
                col("ShipmentDate"),
                "yyyy-MM-dd"
            )
        )

        # ----------------------------------------------------
        # Convert DeliveryDate
        # ----------------------------------------------------

        .withColumn(
            "DeliveryDate",
            to_date(
                col("DeliveryDate"),
                "yyyy-MM-dd"
            )
        )

        # ----------------------------------------------------
        # Calculate DeliveryDays
        # ----------------------------------------------------

        .withColumn(
            "DeliveryDays",
            datediff(
                col("DeliveryDate"),
                col("ShipmentDate")
            )
        )

        # ----------------------------------------------------
        # Weight Category
        # ----------------------------------------------------

        .withColumn(
            "Weight_Category",
            when(
                col("Weight") > 10,
                "Heavy"
            ).otherwise(
                "Normal"
            )
        )

        # ----------------------------------------------------
        # Weight Validation
        # ----------------------------------------------------

        .withColumn(
            "WeightStatus",
            when(
                col("Weight") > 0,
                "Valid"
            ).otherwise(
                "Invalid"
            )
        )

        # ----------------------------------------------------
        # Processing Timestamp
        # ----------------------------------------------------

        .withColumn(
            "ProcessedDate",
            current_timestamp()
        )
    )

    return df


