def get_current_target_folder():

    """
    Finds the target used as the baseline.

    Priority:

    1. latest_target.txt
    2. newest versioned target
    3. old target_shipments
    4. no target
    """

    # --------------------------------------------------------
    # OPTION 1
    # Pointer
    # --------------------------------------------------------

    if LATEST_TARGET_POINTER.exists():

        try:

            target_path = Path(
                LATEST_TARGET_POINTER.read_text(
                    encoding="utf-8"
                ).strip()
            )

            if target_path.exists():

                print()
                print("Current target:")
                print(target_path)

                return target_path

        except Exception as e:

            print(
                "Warning: Could not read "
                f"latest target pointer: {e}"
            )


    # --------------------------------------------------------
    # OPTION 2
    # Newest version
    # --------------------------------------------------------

    versions = [
        p
        for p in TARGET_VERSIONS_FOLDER.iterdir()
        if p.is_dir()
    ]

    if versions:

        versions.sort(
            key=lambda p: p.stat().st_mtime,
            reverse=True
        )

        newest = versions[0]

        print()
        print("Current target:")
        print(newest)

        return newest


    # --------------------------------------------------------
    # OPTION 3
    # Legacy target
    # --------------------------------------------------------

    if LEGACY_TARGET_FOLDER.exists():

        print()
        print("Using existing legacy target:")
        print(LEGACY_TARGET_FOLDER)

        return LEGACY_TARGET_FOLDER


    # --------------------------------------------------------
    # OPTION 4
    # First run
    # --------------------------------------------------------

    print()
    print("No existing target found.")
    print("This will be treated as the first ETL run.")

    return None


