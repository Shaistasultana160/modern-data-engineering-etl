def cleanup_old_versions(
    folder,
    retention
):

    try:

        versions = [
            p
            for p in folder.iterdir()
            if p.is_dir()
        ]

        versions.sort(
            key=lambda p: p.stat().st_mtime,
            reverse=True
        )

        old_versions = versions[retention:]

        for old in old_versions:

            try:

                shutil.rmtree(old)

                print(
                    f"Removed old version: "
                    f"{old.name}"
                )

            except Exception as e:

                print(
                    f"Warning: Could not remove "
                    f"{old.name}: {e}"
                )

    except Exception as e:

        print(
            f"Warning: Version cleanup failed: {e}"
        )


